def execute():
	seed_country_codes()


def seed_country_codes():
	created = 0
	updated = 0
	for code, name in COUNTRY_CODES:
		if frappe.db.exists("Country Code", code):
			current = frappe.db.get_value("Country Code", code, "country_name")
			if current != name:
				frappe.db.set_value("Country Code", code, "country_name", name, update_modified=False)
				updated += 1
			continue

		doc = frappe.get_doc(
			{
				"doctype": "Country Code",
				"country_code": code,
				"country_name": name,
			}
		)
		doc.insert(ignore_permissions=True)
		created += 1

	frappe.db.commit()
	return {"created": created, "updated": updated, "total": len(COUNTRY_CODES)}
